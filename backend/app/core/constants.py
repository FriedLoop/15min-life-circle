# ---------------------------------------------------------------------------
# 检索分页策略
# ---------------------------------------------------------------------------
# 百度地点检索单次最多返回 20 条，翻页会额外消耗配额
# 分类检索下配额账本：日配额 100 次 ÷ (类别数 × 翻页数)
#   10 类 × 1 页 = 10 次  → 10 次分析/日
#   10 类 × 2 页 = 20 次  →  5 次分析/日
#   10 类 × 3 页 = 30 次  →  3 次分析/日（过于吃紧）
# 取 2 页：既能覆盖密集类别（如药店）的较远设施，又不至于把配额烧穿。
# 稀疏类别（菜市场、小学等）通常不足一页，会自动提前停止，实际消耗更少。
#
# 【已评估、暂不提高翻页数（2026-10-16 决策）】
# 实测证据（scripts/authority_benchmark.py 的政务名录交叉校验）：
#   莞城、虎门两个老城区的「药店 / 幼儿园」检索**全部触到 40 条上限**，
#   且返回结果按相关性而非距离排序——莞城药店那 40 条距离跨 398~1811 m
#   （中位 1211 m），说明半径内仍有同类设施未被返回，且有比已返回者更近的。
#   表现到指标上：覆盖率**虚低**、盲区率**虚高**（与绕行系数问题同向，都偏保守）。
# 未提高的原因：这是配额换精度的取舍，不是可以"顺手改掉"的缺陷。
#   2 页 → 3 页会让地点检索从约 10 次/分析升到约 30 次，而日配额仅 100 次，
#   可用分析次数从约 10 次降到 3 次，评审现场反复演示时可能直接跑不动。
# 适用条件（满足其一再考虑提高）：需要更精确的覆盖率且能接受分析次数骤减；
#   或百度地点检索配额上调。改动时务必同步重跑 docs/测试报告.md 的
#   覆盖率 / 盲区率 / 健康度全部基准数字。
# 注：步行速度、绕行系数等「需按环境调整」的参数统一在
#     app/core/config.py 定义（可被环境变量覆盖），此处不重复
POI_PAGE_SIZE = 20
POI_MAX_PAGES = 2
